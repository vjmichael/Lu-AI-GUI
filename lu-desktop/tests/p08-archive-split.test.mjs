import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=(p)=>readFileSync(new URL(p,import.meta.url),'utf8');
const core=read('../../src-tauri/lu-core/src/native_archive_split.rs');
const host=read('../src-tauri/src/archive_split_desktop.rs');
const app=read('../src-tauri/src/lib.rs');
const ui=read('../web/main.jsx');
const tests=read('../../src-tauri/lu-core/tests/native_archive_split.rs');
test('P08 native split is not advertised as native spanned ZIP/RAR/7z',()=>{
  assert.match(core,/NOT native/);
  assert.match(core,/lu-archive-byte-parts/);
  assert.match(host,/not.*spanned/i);
  assert.match(ui,/not natively\s+spanned ZIP\/RAR\/7z/);
  assert.match(core,/512\*1024\*1024/);
  assert.match(core,/const MAX_PARTS:usize=128/);
});
test('P08 split stores bounded canonical manifest and rehashes source and resumed staging',()=>{
  assert.match(core,/pub fn plan_split\(/);
  assert.match(core,/pub fn split\(/);
  assert.match(core,/fn checked\(m:&Plan\)/);
  assert.match(core,/serde\(deny_unknown_fields\)/);
  assert.match(core,/if plan_split\(root,&m\.source,m\.chunk_size\)\?!=\*m/);
  assert.match(core,/let stage_meta=root\.symlink_metadata\(&stage_name\)/);
  assert.match(core,/exact\(&staging,c\)\?/);
  assert.match(core,/root\.create_dir\(&out\)/);
  assert.match(core,/staging\.hard_link\(MANIFEST,&published,MANIFEST\)/);
  assert.match(tests,/p08_staged_resume_rehashes_every_part_and_refuses_corrupt_intermediates/);
});
test('P08 reassembly refuses unsafe part names and verifies every part before new-file publication',()=>{
  assert.match(core,/pub fn inspect\(/);
  assert.match(core,/pub fn reassemble\(/);
  assert.match(core,/m\.chunks\.len\(\)>MAX_PARTS/);
  assert.match(core,/format!\("part-\{:04\}\.lup",i\+1\)/);
  assert.match(core,/root\.hard_link|destination_root\.hard_link/);
  assert.match(core,/if format!\("\{:x\}",h\.finalize\(\)\)!=m\.sha256/);
  assert.match(tests,/p08_exact_source_parts_and_roundtrip_to_new_output_parent/);
  assert.match(tests,/p08_corrupt_chunk_or_manifest_never_reconstructs_output/);
  assert.match(tests,/p08_refuses_unsafe_names_stale_sources_and_conflicting_destinations/);
});
test('P08 native user approval and OS path pickers guard writes and task journal',()=>{
  assert.match(host,/blocking_pick_file\(\)/);
  assert.match(host,/blocking_pick_folder\(\)/);
  assert.match(host,/pub\(crate\) async fn lu_p08_split_archive\(/);
  assert.match(host,/pub\(crate\) async fn lu_p08_resume_split\(/);
  assert.match(host,/pub\(crate\) async fn lu_p08_reassemble_archive\(/);
  assert.match(host,/physical_file\(&path\)/);
  assert.match(host,/physical_folder\(source_parent\)/);
  assert.match(host,/physical_folder\(&target\)/);
  assert.match(host,/owner\.background_tasks\.complete\(&task\)/);
  assert.match(host,/owner\.background_tasks\.fail\(&task\)/);
  assert.match(app,/archive_split_desktop::lu_p08_split_archive,/);
  assert.match(app,/archive_split_desktop::lu_p08_resume_split,/);
  assert.match(app,/archive_split_desktop::lu_p08_reassemble_archive,/);
  assert.match(ui,/invoke\(names\[mode\]/);
  assert.match(ui,/Split archive into Lu parts/);
  assert.match(ui,/Resume Lu split stage/);
  assert.match(ui,/Reassemble Lu archive parts/);
});
