"""P04 resolved license bundle protects exact verification package provenance."""
import hashlib
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch
from collect_verification_licenses import bundle, Denied, UPSTREAM

HEAD="a"*40

class LicenseBundleTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name)
        app=self.root/"ide/app"
        (app/"node_modules/react").mkdir(parents=True)
        (app/"package.json").write_text('{"name":"lu-ide-test"}',encoding="utf-8")
        (app/"node_modules/react/package.json").write_text(
            '{"name":"react","version":"19.0.0","license":"MIT"}',encoding="utf-8")
        (app/"node_modules/react/LICENSE").write_text(
            "MIT actual package license text\n"+("a"*250),encoding="utf-8")
        (app/"src-tauri").mkdir()
        (app/"src-tauri/Cargo.toml").write_text("[package]\nname='test'\n",encoding="utf-8")
        cargo=self.root/"cargo-test"
        cargo.mkdir()
        (cargo/"LICENSE-MIT").write_text("Cargo MIT license\n"+"b"*250,encoding="utf-8")
        self.cargo=cargo
        sources=self.root/"ide/packaging/upstream-licenses"
        sources.mkdir(parents=True)
        for key in UPSTREAM:
            (sources/key).write_text("Original reviewed upstream license\n"+("L"*300),encoding="utf-8")
        (app/"package-lock.json").write_text('{"name":"lu-ide-test","lockfileVersion":3}'+" "*100,encoding="utf-8")
        (app/"src-tauri/Cargo.lock").write_text("# This file is automatically @generated by Cargo.\n"+"x"*100,encoding="utf-8")
        self.out=self.root/"notices"

    def collect(self,require_complete=False):
        with patch("collect_verification_licenses.cargo_packages",
                   return_value=([("cargo","cfg-if","1.0.0","MIT",self.cargo)],[])):
            return bundle(self.root,self.out,HEAD,require_complete)

    def test_actual_npm_cargo_license_bytes_and_upstream_text_copied(self):
        d=self.collect(True)
        self.assertFalse(d["releaseApproved"])
        self.assertTrue(d["completeForReleaseReview"])
        self.assertFalse(d["licenseLegalReviewApproved"])
        self.assertEqual(d["packageCount"],2)
        self.assertEqual(len(d["upstreamLicenses"]),6)
        for entry in d["resolvedPackages"]:
            self.assertEqual(len(entry["notices"]),1)
            path=self.out/entry["notices"][0]["path"]
            self.assertEqual(hashlib.sha256(path.read_bytes()).hexdigest(),
                             entry["notices"][0]["sha256"])
        self.assertTrue((self.out/"README.txt").is_file())

    def test_missing_license_does_not_fake_review(self):
        (self.root/"ide/app/node_modules/react/LICENSE").unlink()
        d=self.collect()
        self.assertFalse(d["completeForReleaseReview"])
        self.assertTrue(any("react" in e for e in d["unresolved"]))

    def test_strict_mode_denies_missing_license_without_any_output(self):
        (self.root/"ide/app/node_modules/react/LICENSE").unlink()
        with self.assertRaisesRegex(Denied,"unreviewed_resolved_dependency_notices"):
            self.collect(True)
        self.assertFalse(self.out.exists())

    def test_symlinked_external_notice_is_not_read(self):
        file=self.root/"ide/app/node_modules/react/LICENSE"
        file.unlink()
        external=self.root/"secret"
        external.write_text("confidential contents",encoding="utf-8")
        try:
            file.symlink_to(external)
        except (OSError,NotImplementedError):
            self.skipTest("runner prohibits symlink fixture")
        d=self.collect()
        self.assertFalse(d["completeForReleaseReview"])
        self.assertNotIn("confidential contents",
                         (self.out/"inventory.json").read_text(encoding="utf-8"))

    def test_changed_upstream_review_text_cannot_pass(self):
        (self.root/"ide/packaging/upstream-licenses/LLVM-18.1.8-LICENSE.txt").unlink()
        with self.assertRaisesRegex(Denied,"required_upstream_license_missing"):
            self.collect()

    def test_existing_output_is_never_overwritten(self):
        self.out.mkdir()
        with self.assertRaisesRegex(Denied,"output_must_be_new"):
            self.collect()

if __name__=="__main__":
    unittest.main()
