import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read = rel => readFileSync(new URL("../"+rel,import.meta.url),"utf8");
const workflow=read(".github/workflows/lu-core-c62a-windows-browser-candidate.yml");
const candidate=read("lu-desktop/scripts/assemble-browser-ci-candidate.mjs");
const stage=read("lu-desktop/scripts/stage-browser-runtime.mjs");
const desktop=read("lu-desktop/src-tauri/src/native_browser_host.rs");
test("C6.2A candidate is one exact-SHA batch, not automatic trust",()=>{
  const events=workflow.split("\non:\n")[1].split("\npermissions:")[0];
  assert.match(events,/workflow_dispatch:/);assert.match(events,/workflow_call:/);
  assert.doesNotMatch(events,/push:|pull_request:|pull_request_target:/);
  assert.match(workflow,/github.sha/);
  assert.match(workflow,/node scripts\/verify-source-tree.mjs/);
  assert.match(workflow,/playwright@1\.64\.1/);
  assert.match(workflow,/cli\.js install --no-shell chromium/);
  assert.match(workflow,/assemble-browser-ci-candidate\.mjs/);
  assert.match(workflow,/LU_BROWSER_REQUIRE_CANDIDATE: '1'/);
  assert.match(workflow,/browser-ci-candidate\.test\.mjs/);
  assert.match(workflow,/browser-ci-executable\.test\.mjs/);
  assert.match(workflow,/candidate-summary\.json/);
  assert.match(workflow,/C62A_CANDIDATE_UNAPPROVED=1/);
  assert.doesNotMatch(workflow,/continue-on-error: true|C62A_BROWSER_PRODUCTION_APPROVED=1/);
});
test("candidate never masquerades as an approved browser manifest",()=>{
  assert.match(candidate,/status:'candidate'/);
  assert.match(candidate,/playwrightVersion:expectedVersion/);
  assert.match(candidate,/sha256:hash\.digest\('hex'\)/);
  assert.match(candidate,/copyRegular\(process\.execPath/);
  assert.match(candidate,/copyTree\(playwrightCore/);
  assert.match(candidate,/copyRegular\(browserWorker/);
  assert.match(stage,/manifest\.status!=='reviewed'/);
  assert.match(stage,/LU_BROWSER_MANIFEST_SHA256/);
  assert.match(stage,/hash\.digest\('hex'\)!==f\.sha256/);
  assert.match(desktop,/EMBEDDED_BROWSER_MANIFEST/);
  assert.match(desktop,/manifest\.status!="reviewed"/);
  assert.match(desktop,/package_verified\(\)/);
});
test("C6.2A keeps actual native human permission & executable grant gate",()=>{
  const native=read("lu-desktop/src-tauri/src/lib.rs");
  const model=read("lu-desktop/src-tauri/src/browser_model_desktop.rs");
  assert.match(native,/browser_runtime\.require_launch_ready\(\)\?/);
  assert.match(native,/browser_authority\.open_user_task/);
  assert.match(native,/Read-only Browser grant/);
  assert.match(native,/\.blocking_show\(\)/);
  assert.match(model,/ToolEffect::NetworkRead/);
  assert.match(model,/BrowserReadOnlyPolicy/);
  assert.doesNotMatch(workflow,/LU_BROWSER_MANIFEST_SHA256:/);
});
