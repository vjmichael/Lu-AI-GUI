//! TOOLS-01 next primitive: host-approved, no-clobber transfer of regular files.
//!
//! This is NOT an LLM tool and DOES NOT grant filesystem authority.
//! Host must bind exact source and target to a persisted user turn, durable
//! effect journal and trusted single-directory handle before calling this.
//! Moving a file uses a same-directory hard link then source unlink. An
//! unlink failure leaves BOTH names visible and must be reconciled as UNCERTAIN.
use cap_std::fs::{Dir, OpenOptions};
use sha2::{Digest, Sha256};
use std::{io::{Read, Write}, path::Path};

pub const MAX_TRANSFER_BYTES: u64 = 32 * 1024 * 1024;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TransferError {
    InvalidName,
    SameTarget,
    InvalidStage,
    SourceUnavailable,
    SourceNotRegular,
    TooLarge,
    TargetExists,
    StageExists,
    Io(String),
    PublishedNeedsReconciliation,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TransferReceipt {
    pub source: String,
    pub target: String,
    pub bytes: u64,
    pub sha256: String,
    pub source_removed: bool,
}

/// Only a single filename is accepted. Parent selection is host-owned.
fn plain_filename(s: &str) -> bool {
    !s.is_empty() && s.len() <= 255 && s != "." && s != ".."
        && !s.starts_with(".lu-stage-")
        && !s.ends_with('.') && !s.ends_with(' ')
        && !s.chars().any(|c| c.is_control() || matches!(c, '/' | '\\' | ':'))
        && !Path::new(s).is_absolute()
}
fn stage_id_ok(s: &str) -> bool {
    (16..=128).contains(&s.len()) &&
        s.bytes().all(|c| c.is_ascii_alphanumeric() || c == b'-' || c == b'_')
}
fn verify(root: &Dir, name: &str) -> Result<cap_std::fs::File, TransferError> {
    let m = root.symlink_metadata(name).map_err(|_| TransferError::SourceUnavailable)?;
    if !m.is_file() || m.file_type().is_symlink() {
        return Err(TransferError::SourceNotRegular);
    }
    if m.len() > MAX_TRANSFER_BYTES { return Err(TransferError::TooLarge); }
    let file = root.open(name).map_err(|_| TransferError::SourceUnavailable)?;
    let opened = file.metadata().map_err(|e| TransferError::Io(e.to_string()))?;
    if !opened.is_file() { return Err(TransferError::SourceNotRegular); }
    if opened.len() > MAX_TRANSFER_BYTES { return Err(TransferError::TooLarge); }
    Ok(file)
}
fn source_hash(mut file: cap_std::fs::File) -> Result<(u64, String), TransferError> {
    let mut hash = Sha256::new();
    let mut size = 0_u64;
    let mut buf = [0_u8; 64 * 1024];
    loop {
        let n = file.read(&mut buf).map_err(|e| TransferError::Io(e.to_string()))?;
        if n == 0 { break; }
        size += n as u64;
        if size > MAX_TRANSFER_BYTES { return Err(TransferError::TooLarge); }
        hash.update(&buf[..n]);
    }
    Ok((size, format!("{:x}", hash.finalize())))
}
fn preflight(root: &Dir, from: &str, to: &str) -> Result<(), TransferError> {
    if !plain_filename(from) || !plain_filename(to) { return Err(TransferError::InvalidName); }
    if from.eq_ignore_ascii_case(to) { return Err(TransferError::SameTarget); }
    // Refuse an existing target including a symlink/dangling symlink.
    match root.symlink_metadata(to) {
        Ok(_) => Err(TransferError::TargetExists),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(e) => Err(TransferError::Io(e.to_string())),
    }
}

/// Copy a regular file into a NEW same-directory target, never overwriting.
/// Stage id must be generated by the host; the effect journal owns the lifecycle.
/// Hard-link publication is atomic with no-clobber semantics.
pub fn copy_new_in_dir(
    root: &Dir, source: &str, target: &str, host_stage_id: &str
) -> Result<TransferReceipt, TransferError> {
    preflight(root, source, target)?;
    if !stage_id_ok(host_stage_id) { return Err(TransferError::InvalidStage); }
    let mut input = verify(root, source)?;
    let stage = format!(".lu-stage-{host_stage_id}.tmp");
    let mut options = OpenOptions::new();
    options.create_new(true).write(true);
    let mut output = root.open_with(&stage, &options).map_err(|e| {
        if e.kind() == std::io::ErrorKind::AlreadyExists { TransferError::StageExists }
        else { TransferError::Io(e.to_string()) }
    })?;
    let result = (|| {
        let mut hasher = Sha256::new();
        let mut count = 0_u64;
        let mut buf = [0_u8; 64 * 1024];
        loop {
            let n = input.read(&mut buf).map_err(|e| TransferError::Io(e.to_string()))?;
            if n == 0 { break; }
            count += n as u64;
            if count > MAX_TRANSFER_BYTES { return Err(TransferError::TooLarge); }
            output.write_all(&buf[..n]).map_err(|e| TransferError::Io(e.to_string()))?;
            hasher.update(&buf[..n]);
        }
        // Source changed during read: refuse publication. Hash represents the
        // actual copied bytes; a live mutable source cannot promise a snapshot.
        if input.metadata().map_err(|e| TransferError::Io(e.to_string()))?.len() != count {
            return Err(TransferError::Io("source size changed during copy".into()));
        }
        output.sync_all().map_err(|e| TransferError::Io(e.to_string()))?;
        Ok((count, format!("{:x}", hasher.finalize())))
    })();
    drop(output);
    let (bytes, sha256) = match result {
        Ok(x) => x,
        Err(e) => { let _ = root.remove_file(&stage); return Err(e); }
    };
    if let Err(e) = root.hard_link(&stage, root, target) {
        let _ = root.remove_file(&stage);
        return Err(if e.kind() == std::io::ErrorKind::AlreadyExists {
            TransferError::TargetExists
        } else { TransferError::Io(e.to_string()) });
    }
    root.remove_file(&stage).map_err(|_| TransferError::PublishedNeedsReconciliation)?;
    Ok(TransferReceipt {
        source: source.into(), target: target.into(), bytes, sha256,
        source_removed: false,
    })
}

/// Move a regular file to a NEW name within the same approved directory.
/// If unlink fails after publication, the caller MUST reconcile the receipt
/// and both paths before retry; no implicit delete/rollback is performed.
pub fn move_new_in_dir(root: &Dir, source: &str, target: &str)
    -> Result<TransferReceipt, TransferError>
{
    preflight(root, source, target)?;
    let file = verify(root, source)?;
    let (bytes, sha256) = source_hash(file)?;
    root.hard_link(source, root, target).map_err(|e| {
        if e.kind() == std::io::ErrorKind::AlreadyExists { TransferError::TargetExists }
        else { TransferError::Io(e.to_string()) }
    })?;
    root.remove_file(source).map_err(|_| TransferError::PublishedNeedsReconciliation)?;
    Ok(TransferReceipt {
        source: source.into(), target: target.into(), bytes, sha256,
        source_removed: true,
    })
}
